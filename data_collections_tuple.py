# Data collections - Tuple
# Tuple items are ordered, unchangeable, and allow duplicate values

# Touple can be created via more than one way
my_tuple = tuple(["apple", "banana", "orange"])
my_tuple = ("apple", "banana", "orange") # preferred

print(my_tuple)

print(len(my_tuple))

print(my_tuple[0])

